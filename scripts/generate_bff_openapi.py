"""Write (or check) docs/api/cortex-bff.openapi.json: the BFF's full OpenAPI document, as app.openapi() renders it.

Cortex generates its client types from this file at its pinned producer sha (PRODUCER_REF). It reads the file from
`../invincible-agent` and never renders the app itself, because the cortex box has no Python.
Architect ruling 2026-10-24, item 5: "(a). Commit the BFF's full /openapi.json on master, regenerated by a test that
fails when it drifts from app.openapi()."

    uv run python scripts/generate_bff_openapi.py          # write
    uv run python scripts/generate_bff_openapi.py --check  # exit 1 if the committed file is stale

tests/test_bff_openapi_is_current.py makes the same comparison.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DOC_PATH = ROOT / "docs" / "api" / "cortex-bff.openapi.json"


def build() -> dict:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from src.iagent import gateway

    return gateway.app.openapi()


def serialise(doc: dict) -> str:
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def read_committed() -> str | None:
    try:
        return DOC_PATH.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def main(argv: list[str]) -> int:
    text = serialise(build())
    if "--check" in argv:
        if read_committed() != text:
            print(f"{DOC_PATH.relative_to(ROOT)} is stale: run scripts/generate_bff_openapi.py", file=sys.stderr)
            return 1
        return 0
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC_PATH.relative_to(ROOT)} ({len(text)} bytes, {len(json.loads(text)['paths'])} paths)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
