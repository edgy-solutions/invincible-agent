#!/usr/bin/env python3
"""Render board/BOARD.md from board/items/*.md, board/PRIORITIES.md and board/SWEEP.md.

Stdlib only (CI runs it with a bare setup-python). Deterministic: no clock, no environment.

    render_board.py            validate, then write board/BOARD.md
    render_board.py --check    exit 1 with a DRIFT line if the committed file differs
    render_board.py --new-id   print a fresh ULID
"""
from __future__ import annotations

import argparse
import datetime
import re
import secrets
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

ULID_RE = re.compile(r"^[0-9A-HJKMNP-TV-Z]{26}$")
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
LANE_RE = re.compile(r"^[a-z0-9][a-z0-9-]*/\S+$")
PR_RE = re.compile(r"^[a-z0-9-]+#\d+$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
STATUSES = ("open", "claimed", "blocked", "review", "done")
KEYS = frozenset(
    "title feature lane repo status priority blocked_on pr ruling_ref updated".split()
)
CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
HEADER_COMMENT = (
    "<!-- generated by scripts/render_board.py from board/items, "
    "board/PRIORITIES.md, board/SWEEP.md; never edit -->"
)


class BoardError(Exception):
    def __init__(self, errors: list[str]):
        super().__init__("\n".join(errors))
        self.errors = errors


@dataclass
class Item:
    id: str
    title: str
    feature: str
    lane: str
    repo: str
    status: str
    priority: str
    blocked_on: list[str]
    pr: list[str]
    ruling_ref: str
    updated: str
    body: str


@dataclass
class Board:
    features: list[tuple[int, str, str]] = field(default_factory=list)  # rank, slug, name
    priorities: list[str] = field(default_factory=list)
    reorders: list[str] = field(default_factory=list)
    items: dict[str, Item] = field(default_factory=dict)
    swept_at: str = ""
    sweep: list[tuple[str, str]] = field(default_factory=list)


# ---------------------------------------------------------------- parsing helpers

def _cell(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s.startswith("`") and s.endswith("`"):
        s = s[1:-1].strip()
    return s


def _section(text: str, heading: str) -> list[str] | None:
    lines = text.splitlines()
    for i, ln in enumerate(lines):
        if ln.strip() == f"## {heading}":
            out = []
            for nxt in lines[i + 1:]:
                if nxt.startswith("#"):
                    break
                out.append(nxt)
            return out
    return None


def _table_rows(lines: list[str]) -> list[list[str]]:
    """Data rows of a markdown table (header and separator dropped)."""
    rows = []
    for ln in lines:
        s = ln.strip()
        if s.startswith("|"):
            rows.append([_cell(c) for c in s.strip("|").split("|")])
    if rows:
        rows = rows[1:]
    return [r for r in rows if not all(re.fullmatch(r":?-{3,}:?", c) for c in r)]


def _split_frontmatter(text: str) -> tuple[dict[str, str] | None, str, list[str]]:
    errs: list[str] = []
    lines = text.replace("\r\n", "\n").split("\n")
    if lines[0].strip() != "---":
        return None, "", ["frontmatter: file must start with a --- line"]
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        return None, "", ["frontmatter: no closing --- line"]
    fm: dict[str, str] = {}
    for ln in lines[1:end]:
        if not ln.strip():
            continue
        if ":" not in ln:
            errs.append(f"frontmatter: line without a colon: {ln!r}")
            continue
        k, v = ln.split(":", 1)
        k = k.strip()
        if k in fm:
            errs.append(f"{k}: duplicate key")
        fm[k] = v.strip()
    return fm, "\n".join(lines[end + 1:]), errs


def _flow_list(v: str) -> list[str] | None:
    v = v.strip()
    if not (v.startswith("[") and v.endswith("]")):
        return None
    inner = v[1:-1].strip()
    if not inner:
        return []
    return [p.strip() for p in inner.split(",")]


def _valid_date(v: str) -> bool:
    if not DATE_RE.match(v):
        return False
    try:
        datetime.date.fromisoformat(v)
    except ValueError:
        return False
    return True


# ---------------------------------------------------------------- load

def _load_priorities(bd: Path, board: Board, errors: list[str]) -> None:
    pfile = "PRIORITIES.md"
    try:
        ptext = (bd / pfile).read_text(encoding="utf-8")
    except OSError as e:
        errors.append(f"{pfile}: file: cannot read ({e.__class__.__name__})")
        return
    sec = _section(ptext, "Features")
    if sec is None:
        errors.append(f"{pfile}: Features: missing '## Features' section")
    else:
        seen = set()
        for r in _table_rows(sec):
            if len(r) < 3 or not r[0].isdigit():
                errors.append(f"{pfile}: Features: bad row {r!r}")
                continue
            rank, slug, name = int(r[0]), r[1], r[2]
            if not SLUG_RE.match(slug):
                errors.append(f"{pfile}: Features: bad slug {slug!r}")
            if slug in seen:
                errors.append(f"{pfile}: Features: duplicate slug {slug!r}")
            seen.add(slug)
            board.features.append((rank, slug, name))
        ranks = sorted(f[0] for f in board.features)
        if ranks != list(range(1, len(ranks) + 1)):
            errors.append(f"{pfile}: Features: ranks must run 1..N, contiguous and unique")
        if not board.features:
            errors.append(f"{pfile}: Features: no features")
        board.features.sort()
    sec = _section(ptext, "Item priority")
    if sec is None:
        errors.append(f"{pfile}: Item priority: missing '## Item priority' section")
    else:
        for r in _table_rows(sec):
            if not r or not r[0]:
                errors.append(f"{pfile}: Item priority: bad row {r!r}")
                continue
            if r[0] in board.priorities:
                errors.append(f"{pfile}: Item priority: duplicate {r[0]!r}")
            board.priorities.append(r[0])
        if not board.priorities:
            errors.append(f"{pfile}: Item priority: no priorities")
    sec = _section(ptext, "Reorders")
    if sec is None:
        errors.append(f"{pfile}: Reorders: missing '## Reorders' section")
    else:
        for ln in sec:
            s = ln.strip()
            if s.startswith("-"):
                if _valid_date(s[1:].strip()[:10]):
                    board.reorders.append(s)
                else:
                    errors.append(f"{pfile}: Reorders: bullet must begin '- YYYY-MM-DD': {s[:40]!r}")
        if not board.reorders:
            errors.append(f"{pfile}: Reorders: at least one dated bullet is required")


def load(board_dir) -> Board:
    bd = Path(board_dir)
    errors: list[str] = []
    board = Board()
    _load_priorities(bd, board, errors)
    slugs = {f[1] for f in board.features}

    idir = bd / "items"
    if not idir.is_dir():
        errors.append("items: dir: board/items does not exist")
        files = []
    else:
        files = sorted(idir.glob("*.md"))  # non-.md files (.gitkeep) are ignored
    parsed: dict[str, tuple[str, dict[str, str], str]] = {}
    for p in files:
        fname = f"items/{p.name}"
        if not ULID_RE.match(p.stem):
            errors.append(f"{fname}: filename: not a 26-char Crockford ULID")
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as e:
            errors.append(f"{fname}: file: cannot read ({e.__class__.__name__})")
            continue
        fm, body, ferrs = _split_frontmatter(text)
        errors.extend(f"{fname}: {e}" for e in ferrs)
        if fm is not None:
            parsed[p.stem] = (fname, fm, body)

    ids = set(parsed)
    for iid in sorted(parsed):
        fname, fm, body = parsed[iid]
        n0 = len(errors)

        def err(field_: str, msg: str, fname=fname) -> None:
            errors.append(f"{fname}: {field_}: {msg}")

        for k in sorted(KEYS - fm.keys()):
            err(k, "missing key")
        for k in sorted(fm.keys() - KEYS):
            err(k, "unknown key")
        g = fm.get
        if "title" in fm and not fm["title"]:
            err("title", "must be non-empty")
        if "feature" in fm and fm["feature"] not in slugs:
            err("feature", f"unknown feature {fm['feature']!r}")
        if "repo" in fm and not SLUG_RE.match(fm["repo"]):
            err("repo", f"bad repo {fm['repo']!r}")
        status = g("status", "")
        if "status" in fm and status not in STATUSES:
            err("status", f"unknown status {status!r}")
        if "priority" in fm and fm["priority"] not in board.priorities:
            err("priority", f"unknown priority {fm['priority']!r}")
        if "lane" in fm:
            lane = fm["lane"]
            if lane:
                if not LANE_RE.match(lane):
                    err("lane", f"must be <repo>/<branch>, got {lane!r}")
            elif status != "open":
                err("lane", "empty lane is allowed only when status is open")
        blocked: list[str] = []
        if "blocked_on" in fm:
            bl = _flow_list(fm["blocked_on"])
            if bl is None:
                err("blocked_on", "must be a flow list like [] or [a, b]")
            else:
                blocked = bl
                for e in bl:
                    if e.startswith("chris:"):
                        if not e[len("chris:"):].strip():
                            err("blocked_on", "chris: entry needs a non-empty what")
                    elif e == iid:
                        err("blocked_on", "item cannot block on itself")
                    elif e not in ids:
                        err("blocked_on", f"unknown item id {e!r}")
                if status in STATUSES and (status == "blocked") != bool(bl):
                    err("blocked_on", "must be non-empty if and only if status is blocked")
        prs: list[str] = []
        if "pr" in fm:
            pl = _flow_list(fm["pr"])
            if pl is None:
                err("pr", "must be a flow list")
            else:
                prs = pl
                for e in pl:
                    if not PR_RE.match(e):
                        err("pr", f"bad entry {e!r}, want <repo>#<n>")
                if status == "review" and not pl:
                    err("pr", "status review needs at least one pr")
        if "updated" in fm and not _valid_date(fm["updated"]):
            err("updated", f"not a valid YYYY-MM-DD date: {fm['updated']!r}")
        if not body.strip():
            err("body", "must be non-empty")
        if len(errors) == n0:
            board.items[iid] = Item(
                id=iid, title=fm["title"], feature=fm["feature"], lane=fm["lane"],
                repo=fm["repo"], status=status, priority=fm["priority"],
                blocked_on=blocked, pr=prs, ruling_ref=fm["ruling_ref"],
                updated=fm["updated"], body=body.strip(),
            )

    sfile = "SWEEP.md"
    try:
        stext = (bd / sfile).read_text(encoding="utf-8")
    except OSError as e:
        errors.append(f"{sfile}: file: cannot read ({e.__class__.__name__})")
        stext = None
    if stext is not None:
        fm, body, ferrs = _split_frontmatter(stext)
        errors.extend(f"{sfile}: {e}" for e in ferrs)
        if fm is not None:
            if "swept_at" not in fm:
                errors.append(f"{sfile}: swept_at: missing key")
            else:
                board.swept_at = fm["swept_at"]
            for r in _table_rows(body.splitlines()):
                if len(r) < 2:
                    errors.append(f"{sfile}: row: bad row {r!r}")
                elif r[0] not in ids:
                    errors.append(f"{sfile}: item: unknown item id {r[0]!r}")
                else:
                    board.sweep.append((r[0], r[1]))

    if errors:
        raise BoardError(errors)
    return board


# ---------------------------------------------------------------- render

def render(board: Board) -> str:
    rank = {slug: r for r, slug, _ in board.features}
    fname = {slug: name for _, slug, name in board.features}
    prio = {p: i for i, p in enumerate(board.priorities)}
    items = board.items

    def key(it: Item):
        return (rank[it.feature], prio[it.priority], it.id)

    def link(it: Item) -> str:
        return f"[{it.title}](items/{it.id}.md)"

    flags: dict[str, list[str]] = {}
    derived: list[str] = []
    for it in sorted(items.values(), key=key):
        if it.status == "blocked":
            for b in it.blocked_on:
                if b in items and items[b].status == "done":
                    msg = f"blocker {items[b].title} is done"
                    flags.setdefault(it.id, []).append(msg)
                    derived.append(f"- {link(it)}: {msg}")
    swept: list[str] = []
    for iid, text in board.sweep:
        flags.setdefault(iid, []).append(text)
        swept.append(f"- {link(items[iid])}: {text}")

    counts = {s: 0 for s in STATUSES}
    for it in items.values():
        counts[it.status] += 1
    out = ["# Board", "", HEADER_COMMENT, ""]
    out.append(
        f"Sweep: {board.swept_at or 'never swept'} · {len(items)} items · "
        + ", ".join(f"{counts[s]} {s}" for s in STATUSES)
    )
    out.append("")

    out += ["## Waiting on Chris", ""]
    waiting = []
    for it in sorted(items.values(), key=key):
        if it.status == "done":
            continue
        for b in it.blocked_on:
            if b.startswith("chris:"):
                waiting.append(
                    f"- {link(it)} — {b[len('chris:'):].strip()} · "
                    f"{fname[it.feature]} · {it.lane or 'unclaimed'}"
                )
    out += waiting or ["(none)"]
    out.append("")

    out += ["## Flags", ""]
    out += ["### derived from items", ""] + (derived or ["(none)"]) + [""]
    out += ["### from SWEEP.md", ""] + (swept or ["(none)"]) + [""]

    def line(it: Item) -> str:
        parts = [it.lane or "unclaimed", it.priority]
        if it.pr:
            parts.append("PR " + ", ".join(it.pr))
        if it.blocked_on:
            parts.append(
                "blocked on "
                + ", ".join(link(items[b]) if b in items else b for b in it.blocked_on)
            )
        parts.append(f"updated {it.updated}")
        s = f"- {link(it)} — " + " · ".join(parts)
        for f in flags.get(it.id, []):
            s += f" ⚑ {f}"
        return s

    for r, slug, name in board.features:
        its = sorted((i for i in items.values() if i.feature == slug), key=key)
        out += [f"## {r}. {name}", ""]
        if not its:
            out.append("Where it is: no items")
        else:
            c = {s: sum(1 for i in its if i.status == s) for s in STATUSES}
            nxt = next((i for i in its if i.status != "done"), None)
            out.append(
                "Where it is: "
                + " · ".join(f"{c[s]} {s}" for s in ("blocked", "review", "claimed", "open", "done"))
                + "; next: " + (nxt.title if nxt else "nothing")
            )
        out.append("")
        for st in ("blocked", "review", "claimed", "open"):
            sub = [i for i in its if i.status == st]
            if sub:
                out += [f"### {st}", ""] + [line(i) for i in sub] + [""]
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- CLI

def new_id() -> str:
    n = ((int(time.time() * 1000) & ((1 << 48) - 1)) << 80) | secrets.randbits(80)
    return "".join(CROCKFORD[(n >> (5 * i)) & 31] for i in range(25, -1, -1))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Render board/BOARD.md from board/items.")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--new-id", action="store_true")
    ap.add_argument("--board-dir", default=None)
    a = ap.parse_args(argv)
    if a.new_id:
        print(new_id())
        return 0
    bd = Path(a.board_dir) if a.board_dir else Path(__file__).resolve().parent.parent / "board"
    try:
        text = render(load(bd))
    except BoardError as e:
        for ln in e.errors:
            print(ln)
        return 2
    target = bd / "BOARD.md"
    if a.check:
        have = target.read_bytes().decode("utf-8") if target.exists() else None
        if have != text:
            print(f"DRIFT: {target} differs from render; run scripts/render_board.py")
            return 1
        return 0
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
